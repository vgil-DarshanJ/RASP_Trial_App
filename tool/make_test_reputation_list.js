// Makes the trial app's test list for the `malware_reputation` detector,
// using the engine's tools/sign-reputation-list.js:
//
//   node tool/make_test_reputation_list.js [package] [--engine <dir>] [--fixture <file>]
//
//   package    a harmless app that is installed on the test phone and has a
//              launcher icon (default: com.android.chrome)
//   --engine   the rashield-sdk-publish checkout (default: ../../rashield-sdk-publish)
//   --fixture  also write the list as an engine test fixture (JSON)
//
// A throwaway Ed25519 key is generated in a temp directory, the one-entry
// list is signed with it, and the temp directory (with the private key) is
// deleted. Only the signed list and the public key are written, to
// lib/test_reputation_list.dart. Re-run the tool to flag a different app.
const { execFileSync } = require("node:child_process");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const args = process.argv.slice(2);
const option = (name) => {
  const i = args.indexOf(name);
  if (i < 0) return undefined;
  const value = args[i + 1];
  args.splice(i, 2);
  return value;
};
const engineDir = path.resolve(option("--engine") ?? path.join(__dirname, "..", "..", "..", "rashield-sdk-publish"));
const fixturePath = option("--fixture");
const packageName = args[0] ?? "com.android.chrome";

if (!/^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$/.test(packageName)) {
  console.error(`not an Android package name: ${packageName}`);
  process.exit(2);
}
const signTool = path.join(engineDir, "tools", "sign-reputation-list.js");
if (!fs.existsSync(signTool)) {
  console.error(`sign tool not found: ${signTool} (pass --engine <rashield-sdk-publish dir>)`);
  process.exit(2);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "rasp-reputation-"));
let publicKey;
let listJson;
try {
  const run = (...toolArgs) =>
    execFileSync(process.execPath, [signTool, ...toolArgs], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  publicKey = run("keygen", tmp);
  const payloadFile = path.join(tmp, "payload.json");
  const payload = { version: 1, entries: [{ package: packageName, category: "test_entry", severity: "low" }] };
  fs.writeFileSync(payloadFile, JSON.stringify(payload));
  listJson = JSON.stringify(JSON.parse(run("sign", payloadFile, path.join(tmp, "reputation-signing-key.pem"))));
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
console.log(`private key deleted: ${!fs.existsSync(tmp)}`);

if (listJson.includes("'''")) throw new Error("list text cannot be embedded in a Dart raw string");
const dartFile = path.join(__dirname, "..", "lib", "test_reputation_list.dart");
fs.writeFileSync(
  dartFile,
  `// GENERATED by tool/make_test_reputation_list.js. Do not edit; re-run the tool.
//
// Test list for the malware_reputation detector. It names one harmless app
// that is installed on the test phone, so the detector can be seen reporting
// DETECTED. Signed with a throwaway Ed25519 key that was deleted after
// signing; only the public key is kept. To flag another app:
//   node tool/make_test_reputation_list.js <package.name>

/// The app this list flags (harmless; only used to see a detection).
const testReputationPackage = '${packageName}';

/// Base64 X.509 SPKI of the Ed25519 key that signed [testReputationListJson].
const testReputationPublicKey = '${publicKey}';

/// The signed list: \`{"payload": "<JSON text>", "signature": "<Base64>"}\`.
const testReputationListJson = r'''${listJson}''';
`,
);
console.log(`wrote ${path.relative(process.cwd(), dartFile)} for ${packageName}`);

if (fixturePath) {
  fs.writeFileSync(fixturePath, JSON.stringify({ package: packageName, publicKey, list: listJson }, null, 2) + "\n");
  console.log(`wrote fixture ${fixturePath}`);
}
